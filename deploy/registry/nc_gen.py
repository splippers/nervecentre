def page(hosts, svcs, node=None, portals=None):
    if node:
        svcs = [s for s in svcs if s["host"] == node or s.get("shared")]
    groups = {}
    for s in svcs:
        groups.setdefault(s["group"], []).append(s)
    cards = []
    down = [s for s in svcs if s.get("state") == "down"]
    groups = {}
    for s in svcs:
        if s.get("state") != "down":
            groups.setdefault(s["group"], []).append(s)
    for g, items in groups.items():
        cards.append(f"<h2>{html.escape(g)}</h2><div class=\"grid\">")
        for s in items:
            off = s.get("state") == "down"
            cards.append(
                f'<a class="card{" off" if off else ""}" data-id="{s["id"]}" href="/{s["path"]}/">'
                f'<div class="top"><span>{html.escape(s["badge"])}</span><span><i class="dot"></i><b class="st">{"offline" if off else "checking"}</b></span></div>'
                f'<h3>{html.escape(s["title"])}</h3><p>{html.escape(s["desc"])}</p>'
                f'<div class="host">{s["host"]}:{s["port"]} · {s["mode"]}</div></a>')
        cards.append("</div>")
    if down:
        cards.append('<details><summary>Offline (%d) - not running on any host</summary><div class="grid">' % len(down))
        for s in down:
            cards.append(f'<div class="card off"><div class="top"><span>{html.escape(s["badge"])}</span><span><i class="dot"></i>offline</span></div><h3>{html.escape(s["title"])}</h3><p>{html.escape(s["desc"])}</p></div>')
        cards.append('</div></details>')
    others = "".join(f' <a href="{html.escape(u)}">{k.capitalize()} NerveCentre &rarr;</a>'
                     for k, u in (portals or {}).items() if k != node)
    return (PAGE.replace("%NODE%", f" <small>{node.capitalize()}</small>" if node else "")
                .replace("%OTHERS%", others).replace("%CARDS%", "\n".join(cards)))

if __name__ == "__main__":
    a = sys.argv[1:]
    listen = a[a.index("--listen") + 1] if "--listen" in a else "8099"
    hosts, svcs = load(a[0]); out = a[1]; os.makedirs(out, exist_ok=True)
    open(f"{out}/nerve.conf", "w").write(nginx(hosts, svcs, listen, a[a.index("--root") + 1] if "--root" in a else out,
                                        a[a.index("--local") + 1] if "--local" in a else None,
                                        open(a[a.index("--extra") + 1]).read() if "--extra" in a else "", "--default" in a,
                                        a[a.index("--skip") + 1].split(",") if "--skip" in a else (),
                                        a[a.index("--node") + 1] if "--node" in a else None))
    node = a[a.index("--node") + 1] if "--node" in a else None
    with open(a[0], "rb") as f:
        portals = tomllib.load(f).get("portals", {})
    open(f"{out}/index.html", "w").write(page(hosts, svcs, node, portals))
    print(f"wrote {out}/nerve.conf and index.html ({len(svcs)} services)")
